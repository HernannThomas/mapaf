const generateHistory = (
  baseP: number,
  baseT: number,
  baseQ: number,
  baseFreq?: number,
  baseLvl?: number
) => {
  const points = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 60000).toLocaleTimeString('es-CO', {
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
    });
    const noiseP = (Math.random() - 0.5) * (baseP * 0.04);
    const noiseT = (Math.random() - 0.5) * 1.5;
    const noiseQ = (Math.random() - 0.5) * (baseQ * 0.05);

    points.push({
      timestamp: time,
      presion: Math.round((baseP + noiseP) * 10) / 10,
      temperatura: Math.round((baseT + noiseT) * 10) / 10,
      caudal: Math.round((baseQ + noiseQ) * 10) / 10,
      frecuenciaVfd: baseFreq ? Math.round((baseFreq + (Math.random() - 0.5) * 0.8) * 10) / 10 : undefined,
      voltaje: baseFreq ? Math.round(480 + (Math.random() - 0.5) * 6) : undefined,
      corriente: baseFreq ? Math.round(112 + (Math.random() - 0.5) * 8) : undefined,
      vibracion: Math.round((1.8 + (Math.random() - 0.5) * 0.4) * 10) / 10,
      nivel: baseLvl ? Math.round((baseLvl + (Math.random() - 0.5) * 2) * 10) / 10 : undefined,
    });
  }
  return points;
};

